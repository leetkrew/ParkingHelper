using System.Text;
using System.Text.Json;

if (args.Length != 4)
    return Fail("Usage: GoogleAuthConfigGenerator <input-json> <generated-csharp> <generated-plist> <platform>");

var inputPath = Path.GetFullPath(args[0]);
var csharpPath = Path.GetFullPath(args[1]);
var plistPath = Path.GetFullPath(args[2]);
var platform = args[3];

if (!File.Exists(inputPath))
    return Fail($"Google OAuth configuration was not found at '{inputPath}'. " +
                "Create it from GoogleAuth.example.json or pass -p:GoogleAuthConfigPath=...");

try
{
    using var document = JsonDocument.Parse(await File.ReadAllTextAsync(inputPath));
    var root = document.RootElement;
    if (root.ValueKind != JsonValueKind.Object)
        return Fail("Google OAuth configuration must contain a JSON object.");

    ValidateKeys(root, "android", "ios", "macCatalyst");
    var android = ReadPlatform(root, "android", requireReversedClientId: false);
    var ios = ReadPlatform(root, "ios", requireReversedClientId: true);
    var macCatalyst = ReadPlatform(root, "macCatalyst", requireReversedClientId: true);

    Directory.CreateDirectory(Path.GetDirectoryName(csharpPath)!);
    Directory.CreateDirectory(Path.GetDirectoryName(plistPath)!);
    await File.WriteAllTextAsync(csharpPath, GenerateCSharp(android.ClientId, ios.ClientId, ios.ReversedClientId!,
        macCatalyst.ClientId, macCatalyst.ReversedClientId!));
    var reversedClientId = platform switch
    {
        "net10.0-ios" => ios.ReversedClientId!,
        "net10.0-maccatalyst" => macCatalyst.ReversedClientId!,
        _ => string.Empty
    };
    await File.WriteAllTextAsync(plistPath, string.IsNullOrEmpty(reversedClientId)
        ? string.Empty
        : GeneratePartialPlist(reversedClientId));
    return 0;
}
catch (JsonException exception)
{
    return Fail($"Google OAuth configuration is not valid JSON: {exception.Message}");
}
catch (InvalidOperationException exception)
{
    return Fail(exception.Message);
}

static (string ClientId, string? ReversedClientId) ReadPlatform(
    JsonElement root, string platform, bool requireReversedClientId)
{
    if (!root.TryGetProperty(platform, out var value) || value.ValueKind != JsonValueKind.Object)
        throw new InvalidOperationException($"Google OAuth configuration must contain a '{platform}' object.");

    ValidateKeys(value, "clientId", "reversedClientId");
    if (!value.TryGetProperty("clientId", out var clientIdValue))
        throw new InvalidOperationException($"Google OAuth configuration must contain '{platform}.clientId'.");
    var clientId = ReadRequiredString(clientIdValue, $"{platform}.clientId");
    string? reversedClientId = value.TryGetProperty("reversedClientId", out var reversed)
        ? ReadRequiredString(reversed, $"{platform}.reversedClientId")
        : null;
    if (requireReversedClientId && reversedClientId is null)
        throw new InvalidOperationException(
            $"Google OAuth configuration must contain '{platform}.reversedClientId'.");
    return (clientId, reversedClientId);
}

static string ReadRequiredString(JsonElement value, string name)
{
    if (value.ValueKind != JsonValueKind.String || string.IsNullOrWhiteSpace(value.GetString()))
        throw new InvalidOperationException($"Google OAuth configuration value '{name}' must be a non-empty string.");
    return value.GetString()!;
}

static void ValidateKeys(JsonElement value, params string[] allowedKeys)
{
    var allowed = allowedKeys.ToHashSet(StringComparer.Ordinal);
    foreach (var property in value.EnumerateObject())
    {
        if (!allowed.Contains(property.Name))
            throw new InvalidOperationException(
                $"Google OAuth configuration contains unsupported property '{property.Name}'. " +
                "Only OAuth client IDs and reversed client IDs are allowed.");
    }
}

static string GenerateCSharp(
    string androidClientId,
    string iosClientId,
    string iosReversedClientId,
    string macCatalystClientId,
    string macCatalystReversedClientId) =>
    "// <auto-generated />\n" +
    "namespace ParkingHelper.App;\n\n" +
    "internal static class GoogleAuthGeneratedConfiguration\n" +
    "{\n" +
    $"    public const string AndroidClientId = {Literal(androidClientId)};\n" +
    $"    public const string IosClientId = {Literal(iosClientId)};\n" +
    $"    public const string IosReversedClientId = {Literal(iosReversedClientId)};\n" +
    $"    public const string MacCatalystClientId = {Literal(macCatalystClientId)};\n" +
    $"    public const string MacCatalystReversedClientId = {Literal(macCatalystReversedClientId)};\n" +
    "}\n";

static string GeneratePartialPlist(string reversedClientId) =>
    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n" +
    "<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" " +
    "\"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n" +
    "<plist version=\"1.0\">\n<dict>\n" +
    "    <key>CFBundleURLTypes</key>\n    <array>\n        <dict>\n" +
    "            <key>CFBundleURLSchemes</key>\n            <array>\n" +
    $"                <string>{System.Security.SecurityElement.Escape(reversedClientId)}</string>\n" +
    "            </array>\n        </dict>\n    </array>\n</dict>\n</plist>\n";

static string Literal(string value) =>
    "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

static int Fail(string message)
{
    Console.Error.WriteLine($"Google OAuth configuration error: {message}");
    return 1;
}
